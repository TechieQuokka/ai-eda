# Characters of the A00 ROM where they differ from ASCII.
_SPECIAL = {0x5C: "¥", 0x7E: "→", 0x7F: "←"}
# 0xE0-0xFF: Greek letters, umlauts, and symbols, as close as Unicode gets.
_HIGH = "αäβεμσρg√⁻jˣ¢£ñöpqθ∞ΩüΣπxy千万円÷ █"  # noqa: RUF001 - the ROM shows Greek


@cache
def glyph(code: int) -> tuple[int, ...] | None:
    """Eight rows of a character (bit 4 = leftmost dot), or None if the font lacks it."""
    text = _GLYPHS.get(code)
    if text is None:
        return None
    rows = [sum(1 << (4 - i) for i, dot in enumerate(row) if dot == "#") for row in text.split()]
    return (*rows, 0)


def character(code: int) -> str:
    """The text for a character code of the A00 ROM. CGRAM codes 0x00-0x0F read as
    "\\x00".."\\x07" (0x08-0x0F mirror 0x00-0x07); katakana 0xA1-0xDF as half-width
    katakana; codes the ROM leaves blank as a space."""
    if code < 0x10:
        return chr(code & 0x07)
    if code in _SPECIAL:
        return _SPECIAL[code]
    if 0x20 <= code < 0x80:
        return chr(code)
    if 0xA1 <= code <= 0xDF:
        return chr(0xFF61 + code - 0xA1)
    if code >= 0xE0:
        return _HIGH[code - 0xE0]
    return " "


def code_of(char: str) -> int | None:
    """The A00 character code that reads as `char` (the reverse of `character`)."""
    for code, special in _SPECIAL.items():
        if char == special:
            return code
    value = ord(char)
    if 0x20 <= value < 0x80 and value not in _SPECIAL:
        return value
    return None


def columns(code: int) -> tuple[int, ...] | None:
    """The glyph as five columns of eight dots, bit 0 = top row (the byte layout of
    page-addressed pixel displays such as the SSD1306)."""
    rows = glyph(code)
    if rows is None:
        return None
    return tuple(
        sum(1 << y for y, row in enumerate(rows) if row & (1 << (4 - x))) for x in range(5)
    )
